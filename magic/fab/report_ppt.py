def tr(key, lang):
    zh, en = L[key]
    return zh if lang == "zh" else en if lang == "en" else f"{zh} {en}"


def tr2(key, lang):
    """(主標題, 副標題)：中英並列時英文放副標題。"""
    zh, en = L[key]
    return (en, "") if lang == "en" else (zh, en if lang == "both" else "")


def step_label(st, lang):
    if lang == "both":
        zh, en = K.step_name(st, "zh"), K.step_name(st, "en")
        return zh if zh == en else f"{zh} {en}"
    return K.step_name(st, "en" if lang == "en" else "zh")


def params_lines(kind, p, lang):
    if lang == "both":
        zh, en = K.params_text(kind, p, "zh"), K.params_text(kind, p, "en")
        return [(f"{a} / {c}" if a != c else a, b) for (a, b), (c, _) in zip(zh, en)]
    return K.params_text(kind, p, "en" if lang == "en" else "zh")


def _date(a, b=""):
    a = (a or "").replace("-", "/")
    b = (b or "").replace("-", "/")
    return f"{a}–{b[5:] if b[:4] == a[:4] else b}" if b and b != a else a


def template(rec):
    t = dict(rec.get("ppt") or {})
    t.setdefault("title", "")
    t.setdefault("subtitle", "")
    t.setdefault("include", {})
    t.setdefault("skip_steps", [])
    t.setdefault("step_notes", {})
    return t


def default_skip(rec, sample_dir=""):
    """預設不放的步驟：設計、清潔、打線、數據分析這種小步驟，而且沒有參數、照片、說明。"""
    out = []
    for st in rec.get("steps", []):
        if st.get("kind") in ("design", "cleaning", "bonding", "analysis") and not st.get("params") and \
                not st.get("notes") and not st.get("folders"):
            out.append(st["id"])
    return out


