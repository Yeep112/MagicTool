class Builder:
    def __init__(self, lang="zh", title=""):
        self.lang = lang
        self.deck = Deck(title=title)
        self.page = 0
        self.footer = ""

    def content(self, title, sub="", outline=""):
        s = self.deck.slide(outline or title)
        self.page += 1
        s.text(0.6, 0.35, 10.5, 0.7, title, size=26, bold=True, color=NAVY, anchor="b", autofit=False)
        if sub:
            s.text(0.6, 1.02, 10.5, 0.35, sub, size=12, color=MUTED, autofit=False)
        s.line(0.6, 1.42, 12.73, 1.42, LINE, 1.0)
        s.text(0.6, 7.02, 8, 0.3, self.footer, size=9, color="9CA3AF", autofit=False)
        s.text(11.73, 7.02, 1.0, 0.3, str(self.page + 1), size=9, color="9CA3AF", align="r", autofit=False)
        return s

    def chip(self, s, x, y, text, fill, color="FFFFFF", size=10, w=None, h=0.32):
        w = w or max(0.6, 0.11 * len(text) * size / 10 + 0.3)
        s.text(x, y, w, h, text, size=size, bold=True, color=color, fill=fill, radius=0.5, align="c", anchor="m",
               inset=0.02, autofit=False)
        return w

    def kv(self, s, x, y, w, rows, size=12, key_w=1.7, gap=0.36):
        for i, (k, v) in enumerate(rows):
            s.text(x, y + i * gap, key_w, gap, k, size=size - 1, color=MUTED, autofit=False)
            s.text(x + key_w, y + i * gap, w - key_w, gap, v, size=size, bold=True, color=TEXT, autofit=False)
        return y + len(rows) * gap


def _results_rows(rec, lang):
    res = rec.get("results") or {}
    rows = []
    if res.get("r_ohm") is not None:
        rows.append((tr("r", lang), f"{res['r_ohm']:g} Ω"))
    if res.get("sc_contact") is not None:
        rows.append((tr("sc", lang), (tr("yes", lang) if res["sc_contact"] else tr("no", lang)) +
                     (f"（on {res['sc_on']}）" if res.get("sc_on") else "")))
    if res.get("tc_k") is not None:
        rows.append((tr("tc", lang), f"{res['tc_k']:g} K"))
    return rows


def _metals(rec):
    out = []
    for st in rec.get("steps", []):
        if st.get("kind") == "contact":
            for sub in st.get("substeps") or []:
                ly = (sub.get("params") or {}).get("layers")
                if sub.get("kind") == "deposit" and ly:
                    out.append(K.format_layers(ly) + (f" ({sub['params']['method']})" if sub["params"].get("method") else ""))
    return " → ".join(out)


def _rie(rec):
    out = []
    for st in rec.get("steps", []):
        for sub in st.get("substeps") or []:
            p = sub.get("params") or {}
            if sub.get("kind") == "rie" and p.get("time_s") not in (None, ""):
                out.append(f"{p['time_s']} s" + (f" OE {p['oe_nm']:g}" if isinstance(p.get("oe_nm"), (int, float)) else ""))
    return "、".join(out)


def _state(rec, lang):
    st = (rec.get("status") or {}).get("state", "active")
    if lang == "both":
        return f"{K.state_label(st)} {K.state_label(st, 'en')}"
    return K.state_label(st, "en" if lang == "en" else "zh")


