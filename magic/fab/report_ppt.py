def slide_summary(b, it, tmp):
    rec, lang = it["rec"], b.lang
    t, sub = tr2("overview", lang)
    s = b.content(f"{t}　{rec.get('label')}", sub)
    steps = rec.get("steps", [])
    dates = [x.get("date_end") or x.get("date") for x in steps if x.get("date")]
    st = rec.get("status") or {}
    rows = [(tr("type", lang), rec.get("type") or "—"),
            (tr("start", lang), (rec.get("start") or "—").replace("-", "/") + (f" → {max(dates).replace('-', '/')}"
                                                                               if dates else "")),
            (tr("state", lang), _state(rec, lang) + (f"（{st['reason']}）" if st.get("reason") else "")),
            (tr("steps", lang), str(len(steps)))]
    if st.get("next") and st.get("state") == "active":
        rows.append((tr("next", lang), st["next"]))
    rows += _results_rows(rec, lang)
    if _metals(rec):
        rows.append((tr("metal", lang), _metals(rec)))
    y = b.kv(s, 0.6, 1.7, 5.2, rows, size=13, key_w=1.75, gap=0.42)
    img = V.render_png(os.path.join(tmp, f"sum_{abs(hash(rec.get('label'))) % 10**8}.png"), rec, it["outlines"], None,
                       "en" if lang == "en" else "zh", size=(7.6, 4.2), dpi=150)
    s.image(img, 6.0, 1.6, 6.9, 3.85)
    # 流程：彩色小方塊
    ft, _ = tr2("flow", lang)
    s.text(0.6, max(y, 5.55) + 0.05, 4, 0.3, ft, size=11, bold=True, color=MUTED, autofit=False)
    flow = [x for x in steps if x["id"] not in it["tpl"]["skip_steps"]]
    x0, yy = 0.6, max(y, 5.55) + 0.4
    w = min(1.55, (12.13 - 0.08 * (min(len(flow), 8) - 1)) / max(1, min(len(flow), 8)))
    for i, x in enumerate(flow[:16]):
        r, c = divmod(i, 8)
        if r > 1:
            break
        col = K.color(x["kind"]).lstrip("#")
        s.text(x0 + c * (w + 0.08), yy + r * 0.5, w, 0.42, step_label(x, "en" if lang == "en" else "zh"), size=9,
               bold=True, color="FFFFFF", fill=col, radius=0.25, align="c", anchor="m", inset=0.02, autofit=False)


def slides_timeline(b, it):
    rec, lang = it["rec"], b.lang
    rows, kinds = [], []
    for i, st in enumerate(rec.get("steps", []), start=1):
        if st["id"] in it["tpl"]["skip_steps"]:
            continue
        info = K.summary(st, "en" if lang == "en" else "zh")
        rows.append([str(i), step_label(st, lang), _date(st.get("date"), st.get("date_end")), info or "—"])
        kinds.append(st["kind"])
    t, sub = tr2("timeline", lang)
    per = 12
    for k in range(0, max(1, len(rows)), per):
        chunk = rows[k:k + per]
        s = b.content(f"{t}　{rec.get('label')}" + (f"（{k // per + 1}）" if len(rows) > per else ""), sub)
        head = ["#", tr("step", lang), tr("date", lang), tr("content", lang)]
        fills = {(ri, 1): _soft(K.color(kd)) for ri, kd in enumerate(kinds[k:k + per], start=1)}
        s.table(0.6, 1.65, 12.13, [head] + chunk, col_w=[0.5, 2.6, 2.0, 7.0], size=11, header_fill=NAVY,
                row_h=0.4, fills=fills)


def _soft(hexcol, t=0.85):
    h = hexcol.lstrip("#")
    r, g, bb = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return "%02X%02X%02X" % tuple(int(c + (255 - c) * t) for c in (r, g, bb))


def slide_evolution(b, it, tmp):
    rec, lang = it["rec"], b.lang
    steps = rec.get("steps", [])
    keys = [i for i, st in enumerate(steps) if st.get("kind") in ("transfer", "cover", "marker", "contact", "top_gate",
                                                                    "rie", "deposit", "ion_mill")]
    if not keys:
        return
    keys = keys[:6] if len(keys) <= 6 else keys[:5] + [keys[-1]]
    t, sub = tr2("evolution", lang)
    s = b.content(f"{t}　{rec.get('label')}", sub)
    cols = 3 if len(keys) > 4 else 2
    rws = (len(keys) + cols - 1) // cols
    cw, ch = 12.13 / cols, 5.3 / rws
    for n, i in enumerate(keys):
        r, c = divmod(n, cols)
        img = V.render_png(os.path.join(tmp, f"evo_{abs(hash(rec.get('label'))) % 10**8}_{i}.png"), rec, [], i,
                           "en" if lang == "en" else "zh", what="section", size=(5.2, 3.0), dpi=140)
        s.image(img, 0.6 + c * cw, 1.6 + r * ch, cw - 0.15, ch - 0.1)


def slide_step(b, it, idx, tmp):
    rec, lang = it["rec"], b.lang
    st = rec["steps"][idx]
    kind = st["kind"]
    sub = "　·　".join(x for x in (_date(st.get("date"), st.get("date_end")), f"{tr('sample', lang)} {rec.get('label')}") if x)
    s = b.content(f"{idx + 1}. {step_label(st, lang)}", sub, outline=step_label(st, lang))
    b.chip(s, 10.9, 0.55, K.CATEGORIES[K.category(kind)][1 if lang == "en" else 0], K.color(kind).lstrip("#"), size=10)
    y = 1.7
    pr = params_lines(kind, st.get("params"), lang)
    if pr:
        s.text(0.6, y, 5, 0.32, tr("params", lang), size=12, bold=True, color=PINK, autofit=False)
        y = b.kv(s, 0.6, y + 0.38, 5.4, pr, size=12, key_w=1.9, gap=0.36) + 0.15
    subs = st.get("substeps") or []
    if subs:
        s.text(0.6, y, 5, 0.32, tr("subs", lang), size=12, bold=True, color=PINK, autofit=False)
        y += 0.4
        for sub in subs[:8]:
            k = sub["kind"]
            txt = "　".join(f"{a} {v}" for a, v in K.params_text(k, sub.get("params"), "en" if lang == "en" else "zh"))
            s.rect(0.6, y + 0.07, 0.12, 0.22, fill=K.color(k).lstrip("#"))
            name = K.label(k, "en") if lang == "en" else (f"{K.label(k)} {K.label(k, 'en')}" if lang == "both" and
                                                          K.label(k) != K.label(k, "en") else K.label(k))
            s.text(0.82, y, 1.95, 0.36, name, size=11, bold=True, color=TEXT, autofit=False)
            s.text(2.8, y, 3.2, 0.36, txt or "—", size=11, color=TEXT, autofit=False)
            y += 0.38
        y += 0.1
    note = (it["tpl"]["step_notes"].get(st["id"]) or "").strip()
    if st.get("notes"):
        note = (note + "\n" + st["notes"]).strip() if note else st["notes"]
    if note:
        s.text(0.6, y, 5.4, 0.32, tr("notes", lang), size=12, bold=True, color=PINK, autofit=False)
        s.text(0.6, y + 0.38, 5.4, max(0.6, 6.7 - y - 0.4), note, size=12, color=TEXT, fill=SOFT, radius=0.05,
               inset=0.12)
    photos = [p for p in (shrink(x, tmp) for x in step_photos(it["dir"], rec, st)) if p]
    x0, y0, w, h = 6.3, 1.65, 6.43, 5.2
    geo = kind in GEOMETRY and any(x.get("kind") in ("transfer", "cover") for x in rec["steps"][:idx + 1])
    if photos and geo and not note and y < 4.6:                # 左下角放一張「做完這一步」的小剖面
        img = V.render_png(os.path.join(tmp, f"mini_{abs(hash(rec.get('label'))) % 10**8}_{idx}.png"), rec, [], idx,
                           "en" if lang == "en" else "zh", what="section", size=(5.4, 2.9), dpi=130)
        s.image(img, 0.6, y + 0.1, 5.4, 6.75 - y - 0.1)
    if photos:
        n = len(photos)
        cols = 1 if n == 1 else 2
        rws = 1 if n <= 2 else 2
        cw, chh = w / cols, h / rws
        for k, p in enumerate(photos):
            r, c = divmod(k, cols)
            try:
                s.image(p, x0 + c * cw + 0.05, y0 + r * chh + 0.05, cw - 0.1, chh - 0.1, border=LINE)
            except ValueError:
                pass
    elif geo:
        img = V.render_png(os.path.join(tmp, f"step_{abs(hash(rec.get('label'))) % 10**8}_{idx}.png"), rec, [], idx,
                           "en" if lang == "en" else "zh", what="section", size=(6.4, 4.4), dpi=140)
        s.image(img, x0, y0 + 0.2, w, h - 0.4)
        s.text(x0, y0 + h - 0.2, w, 0.3, tr("after", lang), size=10, color=MUTED, align="c", autofit=False)
    else:
        s.text(x0, y0, w, h, tr("nophoto", lang), size=14, color="9CA3AF", fill=SOFT, radius=0.04, align="c",
               anchor="m", autofit=False)


def slide_results(b, it):
    rec, lang = it["rec"], b.lang
    rows = _results_rows(rec, lang)
    if not rows:
        return
    t, sub = tr2("results", lang)
    s = b.content(f"{t}　{rec.get('label')}", sub)
    n = len(rows)
    w = 12.13 / n
    for i, (k, v) in enumerate(rows):
        x = 0.6 + i * w
        s.rect(x + 0.1, 2.0, w - 0.2, 2.6, fill=SOFT, radius=0.06)
        s.text(x + 0.1, 2.25, w - 0.2, 1.4, v, size=40, bold=True, color=PINK, align="c", anchor="m", autofit=False)
        s.text(x + 0.1, 3.7, w - 0.2, 0.6, k, size=14, color=MUTED, align="c", autofit=False)
    res = rec.get("results") or {}
    extra = []
    if res.get("note"):
        extra.append(res["note"])
    if res.get("source"):
        extra.append(f"{tr('measured_at', lang)}：{res['source']}")
    if extra:
        s.text(0.6, 5.0, 12.13, 1.2, "\n".join(extra), size=13, color=TEXT)


