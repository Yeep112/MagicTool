def export(items, path, lang="zh", sections=None, deck_title="", deck_sub="", log=None):
    """items = [{"rec", "dir", "outlines"}]（每顆樣品）。sections = 要放的段落（None = 預設）。回傳 (路徑, 幾頁)。"""
    sections = set(sections if sections is not None else DEFAULT_ON)
    multi = len(items) > 1
    for it in items:
        it["tpl"] = template(it["rec"])
        if not it["tpl"]["skip_steps"] and "skip_steps" not in (it["rec"].get("ppt") or {}):
            it["tpl"]["skip_steps"] = default_skip(it["rec"], it.get("dir"))
        it.setdefault("outlines", [])
        it.setdefault("dir", "")
    labels = "、".join(str(it["rec"].get("label")) for it in items)
    if not deck_title:
        t0 = items[0]["tpl"]["title"] if not multi else ""
        deck_title = t0 or (f"{tr2('compare', lang)[0]}：{labels}" if multi else
                            f"{'Sample' if lang == 'en' else '樣品'} {labels} {tr2('report', lang)[0]}")
    if not deck_sub:
        if not multi and items[0]["tpl"]["subtitle"]:
            deck_sub = items[0]["tpl"]["subtitle"]
        else:
            r0 = items[0]["rec"]
            deck_sub = " · ".join(x for x in ((r0.get("type") if not multi else f"{len(items)} 顆樣品" if lang != "en"
                                               else f"{len(items)} samples"), r0.get("user") or "") if x)
    b = Builder(lang, deck_title)
    tmp = tempfile.mkdtemp(prefix="magic_ppt_")
    try:
        if "cover" in sections:
            slide_cover(b, items, deck_title, deck_sub)
        if multi and "compare" in sections:
            slides_compare(b, items, tmp)
        for it in items:
            inc = {k: it["tpl"]["include"].get(k, k in sections) for k, _, _ in SECTIONS}
            b.footer = f"{deck_title}　·　{it['rec'].get('label')}" if multi else deck_title
            if multi:
                section_divider(b, it)
            if inc["summary"]:
                slide_summary(b, it, tmp)
            if inc["timeline"]:
                slides_timeline(b, it)
            if inc["evolution"]:
                slide_evolution(b, it, tmp)
            if inc["steps"]:
                for i, st in enumerate(it["rec"].get("steps", [])):
                    if st["id"] not in it["tpl"]["skip_steps"]:
                        slide_step(b, it, i, tmp)
                        if log:
                            log(f"{it['rec'].get('label')}：{step_label(st, lang)}")
            if inc["results"]:
                slide_results(b, it)
            if inc["reviews"]:
                slide_reviews(b, it)
        b.deck.save(path)
    finally:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)
    return path, len(b.deck.slides)
