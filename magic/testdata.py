def etching_csv(path):
    from .etching.calc import compute_rates, make_row, HEADERS
    import csv
    from datetime import datetime, timedelta
    t0 = datetime(2026, 11, 1, 10, 0, 0)
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(HEADERS)
        for k, (m, pw, b, pr, ty, nm, gas, hb, ha, mb, ma, t) in enumerate(ETCH_ROWS):
            rates = compute_rates(hb, ha, t, marker_before=mb, marker_after=ma, reference="marker")
            w.writerow(make_row(rates, hbn_before=hb, hbn_after=ha, t=t, marker_before=mb, marker_after=ma,
                                method=m, power=pw, bias=b, pressure=pr, sample_type=ty, name=nm, gas=gas,
                                when=t0 + timedelta(days=k)))
    return path


def _write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_all(folder):
    """在 folder 底下產生 PPMS / SQUID / Raman / Etching 範例檔，回傳 {名稱: 路徑}。"""
    j = os.path.join
    out = {
        "ppms": ppms_rt(j(folder, "PPMS", "synthetic_300K_2K_300K.dat")),
        "ppms2": ppms_rt_variant(j(folder, "PPMS", "synthetic_sampleB_cool.dat")),
        "squid_mt": squid_mt(j(folder, "SQUID", "synthetic_In_MT_ZFC_FC.dat")),
        "squid_mh": squid_mh(j(folder, "SQUID", "synthetic_In_MH_2K.dat")),
        "raman_mono": raman(j(folder, "Raman", "synthetic_monolayer.txt"), "monolayer"),
        "raman_multi": raman(j(folder, "Raman", "synthetic_multilayer.txt"), "multilayer", seed=6, sep="\t"),
        "raman_hybrid": raman(j(folder, "Raman", "synthetic_hBN_graphene.csv"), "hybrid", seed=7, sep=","),
        "etching": etching_csv(j(folder, "Etching", "etch_rate_log.csv")),
    }
    return out
