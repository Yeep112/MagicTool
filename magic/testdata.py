def _sigmoid(T, Tc, w):
    return 1.0 / (1.0 + np.exp(-(T - Tc) / w))


def ppms_rt(path, seed=1):
    """R–T：300 K 降到 2 K、在 2 K 停留、再升回 300 K（升溫的 Tc 稍高，模擬遲滯）。"""
    rng = np.random.default_rng(seed)
    cool = np.concatenate([np.linspace(300, 20, 400), np.linspace(20, 2, 900)])
    hold = 2.0 + rng.normal(0, 0.0008, 40)
    warm = np.concatenate([np.linspace(2, 20, 900), np.linspace(20, 300, 400)])
    T = np.concatenate([cool, hold, warm]) + rng.normal(0, 0.002, cool.size + hold.size + warm.size)
    Rn = 12.0 + 0.04 * T
    phase = np.concatenate([np.zeros(cool.size + hold.size), np.ones(warm.size)])
    Tc = np.where(phase == 0, TRUTH["ppms_Tc_cool"], TRUTH["ppms_Tc_warm"])
    R = Rn * _sigmoid(T, Tc, TRUTH["ppms_width"]) + rng.normal(0, 0.004, T.size)
    t = np.arange(T.size) * 2.0
    comment = [""] * T.size
    comment[0] = "Start cooling"
    comment[cool.size] = "1"                 # 看起來像數字的註解：舊版會把整欄變成 NaN
    comment[cool.size + hold.size] = "Start warming"
    lines = ["[Header]", "; Synthetic data generated by Magic Tool selftest (not a real measurement)",
             "TITLE,Synthetic PPMS R-T", "BYAPP, Resistivity, Release 1.0 (synthetic)",
             "INFO, Synthetic sample, SAMPLE1", "INFO, 300K_2K_300K, SAMPLE_DESCRIPTION",
             "FILEOPENTIME,0,11/26/2026,1:00 AM", "[Data]",
             "Comment,Time Stamp (sec),Temperature (K),Magnetic Field (Oe),Sample Position (deg),"
             "Bridge 1 Resistance (Ohms),Bridge 1 Excitation (uA),Bridge 2 Resistance (Ohms),"
             "Bridge 3 Resistance (Ohms),"]
    for k in range(T.size):
        lines.append(f"{comment[k]},{t[k]:.1f},{T[k]:.5f},0,0,{R[k]:.6f},100,{R[k] * 2 + 1:.6f},,")
    _write(path, "\n".join(lines) + "\n")
    return path


def ppms_rt_variant(path, Tc=6.6, seed=2):
    """批次比較用：另一個樣品（Tc 不同，只有降溫）。"""
    rng = np.random.default_rng(seed)
    T = np.linspace(15, 2, 700) + rng.normal(0, 0.002, 700)
    R = (30 + 0.1 * T) * _sigmoid(T, Tc, 0.12) + rng.normal(0, 0.01, T.size)
    lines = ["[Header]", "; Synthetic data generated by Magic Tool selftest", "BYAPP, Resistivity, synthetic",
             "[Data]", "Comment,Time Stamp (sec),Temperature (K),Magnetic Field (Oe),Bridge 1 Resistance (Ohms),"]
    for k in range(T.size):
        lines.append(f",{k * 2.0:.1f},{T[k]:.5f},0,{R[k]:.6f},")
    _write(path, "\n".join(lines) + "\n")
    return path


def squid_mt(path, seed=3):
    """M–T：ZFC 升溫 1.8→10 K，接著 FC 降溫 10→1.8 K（10 Oe），銦的 Tc ≈ 3.41 K。

    在 setpoint 附近有溫度幾乎相同的點（舊版「相鄰兩點斜率最大」會在這裡誤判）。"""
    rng = np.random.default_rng(seed)
    hold0 = 1.8 + rng.normal(0, 0.0005, 15)
    zfc = np.linspace(1.8, 10, 420)
    fc = np.linspace(10, 1.8, 420)
    T = np.concatenate([hold0, zfc, fc]) + rng.normal(0, 0.001, hold0.size + zfc.size + fc.size)
    w, Tc = TRUTH["squid_width"], TRUTH["squid_Tc"]
    sc = 1 - _sigmoid(T, Tc, w)
    M_zfc = -2.0e-4 * sc
    M_fc = -0.6e-4 * sc                              # FC 的 Meissner 分率較小
    is_fc = np.concatenate([np.zeros(hold0.size + zfc.size), np.ones(fc.size)]).astype(bool)
    M = np.where(is_fc, M_fc, M_zfc) + 2e-9 * (10 / T) + rng.normal(0, 3e-8, T.size)
    lines = ["[Header]", "; Synthetic data generated by Magic Tool selftest (not a real measurement)",
             "TITLE,Synthetic In M-T", "BYAPP, MPMS3, 1.2 (synthetic)", "INFO, In sphere (synthetic), SAMPLE_MATERIAL",
             "[Data]", "Comment,Time Stamp (sec),Temperature (K),Magnetic Field (Oe),Moment (emu),M. Std. Err. (emu),"]
    for k in range(T.size):
        c = "ZFC" if k == 0 else ("FC" if k == hold0.size + zfc.size else "")
        lines.append(f"{c},{k * 3.0:.1f},{T[k]:.5f},10,{M[k]:.6e},{3e-8:.2e},")
    _write(path, "\n".join(lines) + "\n")
    return path


def squid_mh(path, seed=4):
    """M–H：2 K 磁滯迴線 0 → +300 → −300 → +300 Oe，第一類超導體（Hc ≈ 184 Oe）。"""
    rng = np.random.default_rng(seed)
    H = np.concatenate([np.linspace(0, 300, 151), np.linspace(300, -300, 301), np.linspace(-300, 300, 301)])
    Hc = TRUTH["squid_Hc"]
    k = 2.0e-4 / Hc
    M = np.where(np.abs(H) < Hc, -k * H, 0.0) + 1e-9 * H + rng.normal(0, 2e-8, H.size)
    lines = ["[Header]", "; Synthetic data generated by Magic Tool selftest", "BYAPP, MPMS3, synthetic", "[Data]",
             "Comment,Time Stamp (sec),Temperature (K),Magnetic Field (Oe),Moment (emu),"]
    for i in range(H.size):
        lines.append(f",{i * 2.0:.1f},{2.0 + rng.normal(0, 0.001):.4f},{H[i]:.3f},{M[i]:.6e},")
    _write(path, "\n".join(lines) + "\n")
    return path


def _lor(x, x0, fwhm, A):
    g = fwhm / 2
    return A * g * g / ((x - x0) ** 2 + g * g)


def raman(path, kind="monolayer", seed=5, header=True, sep=" "):
    """kind：monolayer（2D/G ≈ 3、2D FWHM 30）、multilayer（2D 寬、2D/G < 1）、hybrid（加 hBN 1366）。"""
    rng = np.random.default_rng(seed)
    x = np.arange(1100.0, 3000.0, 1.05)
    bg = 1800 + 400 * np.exp(-(x - 1100) / 700) + 0.05 * (x - 1100)
    y = bg + _lor(x, TRUTH["raman_G"], TRUTH["raman_G_fwhm"], 300)
    if kind == "multilayer":
        y += _lor(x, 2700, 55, 240)
    else:
        y += _lor(x, TRUTH["raman_2D"], TRUTH["raman_2D_fwhm"], 900)
    if kind == "hybrid":
        y += _lor(x, TRUTH["raman_hBN"], 9, 500)
    y += rng.normal(0, 4, x.size)
    lines = []
    if header:
        lines += ["# Synthetic Raman spectrum generated by Magic Tool selftest", "Raman shift (cm-1)" + sep + "Intensity"]
    lines += [f"{a:.3f}{sep}{b:.3f}" for a, b in zip(x[::-1], y[::-1])]     # 由大到小：測試自動排序
    _write(path, "\n".join(lines) + "\n")
    return path


